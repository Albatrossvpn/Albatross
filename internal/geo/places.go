var byPlace = map[string][2]float64{}

func init() {
	for _, f := range strings.Fields(places) {
		p := strings.Split(f, "|")
		lat, _ := strconv.ParseFloat(p[1], 64)
		lon, _ := strconv.ParseFloat(p[2], 64)
		byPlace[p[0]] = [2]float64{lat, lon}
	}
}

// Place returns a point in a country: its most populous place.
func Place(code string) (lat, lon float64, ok bool) {
	p, ok := byPlace[strings.ToUpper(code)]
	return p[0], p[1], ok
}
